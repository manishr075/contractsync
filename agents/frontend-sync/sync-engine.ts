import fs from 'fs';
import path from 'path';
import YAML from 'yaml';
import { execSync } from 'child_process';

export interface SyncResult {
  typesPath: string;
  mocksPath: string;
  typesContent: string;
  mocksContent: string;
  compilerSuccess: boolean;
  compilerOutput: string;
  contractVersion: string;
}

export class FrontendSyncEngine {
  public workspaceDir: string;
  public specPath: string;
  public typesPath: string;
  public mocksPath: string;

  constructor(workspaceDir: string) {
    this.workspaceDir = workspaceDir;
    this.specPath = path.resolve(workspaceDir, 'openapi.yaml');
    this.typesPath = path.resolve(workspaceDir, 'src/api.types.ts');
    this.mocksPath = path.resolve(workspaceDir, 'src/mocks.ts');
  }

  public readSpec(): any {
    const raw = fs.readFileSync(this.specPath, 'utf8');
    return YAML.parse(raw);
  }

  /**
   * Generate TypeScript definitions directly from OpenAPI specification
   */
  public generateTypes(): string {
    const spec = this.readSpec();
    const spotSchema = spec.components?.schemas?.Spot;
    if (!spotSchema) {
      throw new Error(`Spot schema missing from ${this.specPath}`);
    }

    const version = spec.info?.version || '1.0.0';
    const lines: string[] = [
      `/**`,
      ` * Auto-generated TypeScript API Definitions for Spot Service API`,
      ` * Contract Version: ${version}`,
      ` * Generated by: ContractSync FrontendSync Agent`,
      ` */`,
      ``
    ];

    // Check if role enum exists
    if (spotSchema.properties?.role?.enum) {
      const roleUnion = spotSchema.properties.role.enum.map((e: string) => `'${e}'`).join(' | ');
      lines.push(`export type SpotRole = ${roleUnion};`);
      lines.push(``);
    }

    lines.push(`export interface Spot {`);

    const requiredFields = new Set(spotSchema.required || []);
    for (const [propName, propDef] of Object.entries<any>(spotSchema.properties || {})) {
      const isRequired = requiredFields.has(propName);
      const isDeprecated = propDef.deprecated === true;

      // JSDoc comment
      lines.push(`  /**`);
      if (propDef.description) {
        lines.push(`   * ${propDef.description}`);
      }
      if (isDeprecated) {
        lines.push(`   * @deprecated Retained for backward compatibility`);
      }
      lines.push(`   */`);

      // Determine TS type
      let tsType = 'string';
      if (propDef.type === 'integer' || propDef.type === 'number') {
        tsType = 'number';
      } else if (propDef.type === 'boolean') {
        tsType = 'boolean';
      } else if (propDef.enum) {
        tsType = propDef.enum.map((e: string) => `'${e}'`).join(' | ');
      }

      lines.push(`  ${propName}${isRequired ? '' : '?'}: ${tsType};`);
    }

    lines.push(`}`);
    lines.push(``);
    lines.push(`export type GetSpotsResponse = Spot;`);
    lines.push(``);

    const generated = lines.join('\n');
    fs.writeFileSync(this.typesPath, generated, 'utf8');
    return generated;
  }

  /**
   * Update frontend mocks to reflect the updated contract
   */
  public updateMocks(): string {
    const spec = this.readSpec();
    const version = spec.info?.version || '1.0.0';

    const hasAvailability = !!spec.components?.schemas?.Spot?.properties?.availability_state;
    const hasRole = !!spec.components?.schemas?.Spot?.properties?.role;
    const hasSpotStatus = !!spec.components?.schemas?.Spot?.properties?.spot_status;

    const mockLines: string[] = [
      `import { Spot } from './api.types.js';`,
      ``,
      `/**`,
      ` * Mock response data adhering to the Spot contract (v${version})`,
      ` * Synchronized by: ContractSync FrontendSync Agent`,
      ` */`,
      `export const mockSpotResponse: Spot = {`,
      `  id: 101,`,
      `  name: 'Library',`
    ];

    if (hasAvailability) {
      mockLines.push(`  availability_state: 'available',`);
    }
    if (hasRole) {
      mockLines.push(`  role: 'admin',`);
    }
    if (hasSpotStatus) {
      mockLines.push(`  // Retained for backward compatibility with legacy consumers`);
      mockLines.push(`  spot_status: 'available',`);
    }

    mockLines.push(`};`);
    mockLines.push(``);
    mockLines.push(`/**`);
    mockLines.push(` * Mock API client handler for GET /api/spots`);
    mockLines.push(` */`);
    mockLines.push(`export async function getMockSpots(): Promise<Spot> {`);
    mockLines.push(`  return Promise.resolve(mockSpotResponse);`);
    mockLines.push(`}`);
    mockLines.push(``);

    const content = mockLines.join('\n');
    fs.writeFileSync(this.mocksPath, content, 'utf8');
    return content;
  }

  /**
   * Run real TypeScript compiler (tsc --noEmit)
   */
  public runCompiler(): { success: boolean; output: string } {
    try {
      // Find tsc or execute npx tsc
      const nodePath = 'C:\\Users\\manis\\.tools\\node';
      const env = {
        ...process.env,
        PATH: `${nodePath};${process.env.PATH || ''}`
      };

      const stdout = execSync('npx tsc --noEmit', {
        cwd: this.workspaceDir,
        env,
        encoding: 'utf8',
        stdio: ['pipe', 'pipe', 'pipe']
      });

      return {
        success: true,
        output: stdout.trim() || 'TypeScript compilation passed with 0 errors.'
      };
    } catch (err: any) {
      const errorOutput = (err.stdout || '') + '\n' + (err.stderr || '') + '\n' + (err.message || '');
      return {
        success: false,
        output: errorOutput.trim()
      };
    }
  }

  /**
   * Perform end-to-end frontend synchronization and verification
   */
  public syncAndVerify(): SyncResult {
    const spec = this.readSpec();
    const version = spec.info?.version || '1.0.0';

    const typesContent = this.generateTypes();
    const mocksContent = this.updateMocks();
    const compiler = this.runCompiler();

    return {
      typesPath: this.typesPath,
      mocksPath: this.mocksPath,
      typesContent,
      mocksContent,
      compilerSuccess: compiler.success,
      compilerOutput: compiler.output,
      contractVersion: version
    };
  }
}
